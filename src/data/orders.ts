const hoursAgo = (h: number) => new Date(Date.now() - h * 3600_000).toISOString();

function trackingChain(orderId: string, upto: number, times: string[]): Order["tracking"] {
  const flow = [
    { status: "placed" as const, title: "Order placed", description: "We received your order and payment." },
    { status: "confirmed" as const, title: "Confirmed by farmers", description: "Growers accepted and reserved your produce." },
    { status: "packed" as const, title: "Harvested & packed", description: "Picked at dawn, packed in compostable crates." },
    { status: "out-for-delivery" as const, title: "Out for delivery", description: "Rider Dhruv is on the way with your basket." },
    { status: "delivered" as const, title: "Delivered", description: "Left fresh at your doorstep." },
  ];
  return flow.map((f, i) => ({
    id: `${orderId}-t${i + 1}`,
    status: f.status,
    title: f.title,
    description: f.description,
    timestamp: times[i],
    completed: i <= upto,
  }));
}

