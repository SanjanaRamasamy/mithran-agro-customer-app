#!/usr/bin/env node
/**
 * Syncs scripts/image-results.json -> src/data/images.ts
 * Preserves the IMG key structure; fills urls that exist.
 */
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "image-results.json");
const DEST = path.join(__dirname, "..", "src", "data", "images.ts");

const KEYS = [
  "p-apple","p-banana","p-spinach","p-tomato","p-carrot","p-broccoli","p-avocado",
  "p-strawberry","p-mango","p-orange","p-grapes","p-bellpepper","p-cucumber",
  "p-potato","p-onion","p-garlic","p-lettuce","p-kale","p-blueberry","p-watermelon",
  "p-pineapple","p-papaya","p-pomegranate","p-mushroom","p-coriander","p-ginger",
  "p-lemon","p-greenpeas","p-cauliflower","p-beetroot",
  "c-fruits","c-vegetables","c-leafy","c-herbs","c-exotic","c-seasonal","c-organic",
  "hero-main","banner-deal","farm-field","f-1","f-2","f-3","f-4",
];

let data = {};
try {
  data = JSON.parse(fs.readFileSync(SRC, "utf8"));
} catch (e) {
  console.error("No image-results.json yet:", e.message);
  process.exit(1);
}

const lines = KEYS.map((k) => {
  const urls = (data[k] && data[k].urls) || [];
  const body = urls.length
    ? "\n    " + urls.map((u) => JSON.stringify(u)).join(",\n    ") + ",\n  "
    : "";
  return `  ${JSON.stringify(k)}: [${body}],`;
}).join("\n");

const out = `/**
 * Central image registry.
 * GENERATED by scripts/sync-images.js — do not edit URLs by hand.
 * Falls back to empty arrays — components render tasteful gradient
 * placeholders when an image URL is missing.
 */
export const IMG: Record<string, string[]> = {
${lines}
};

export function img(key: string, index = 0): string {
  const arr = IMG[key];
  if (!arr || arr.length === 0) return "";
  return arr[index % arr.length];
}

export function gallery(key: string): string[] {
  return IMG[key] ?? [];
}
`;

fs.writeFileSync(DEST, out);
const counts = KEYS.map((k) => `${k}:${((data[k] || {}).urls || []).length}`).join(" ");
console.log("images.ts written.");
console.log(counts);
